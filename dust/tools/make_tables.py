#!/usr/bin/env python3
"""Writes dust/tables.h and dust/tables.cpp: the fixed-point tables the engine
and the screen read, declared once and defined once.

    python3 dust/tools/make_tables.py

Everything here is computed: powers of two, their logarithms and a sine.
Nothing is sampled from any instrument or recording.
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def row(values, per=12):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(values[i:i + per]) + ",")
    return out


def main():
    exp2 = [f"{round(2 ** 30 * 2 ** (i / 256))}u" for i in range(257)]
    log2m = [str(round(65536 * math.log2(1 + i / 256))) for i in range(257)]
    sine = [str(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)]
    head = ["#pragma once", "// Generated by tools/make_tables.py: edit the generator, then regenerate.",
            "#include <opxy/types.hpp>", "", "namespace dust {", "namespace tables {",
            "// 2^(i / 256), Q30.", "extern const opxy::u32 exp2[257];",
            "// log2(1 + i / 256), Q16.", "extern const opxy::i32 log2m[257];",
            "// sin(2 pi i / 1024), Q15, with a guard point.", "extern const opxy::i16 sine[1025];",
            "}", "}", ""]
    (ROOT / "tables.h").write_text("\n".join(head))
    body = ["// Generated by tools/make_tables.py: the tables, defined once (tables.h).", '#include "tables.h"', "",
            "namespace dust {", "namespace tables {",
            "const opxy::u32 exp2[257] = {", *row(exp2, 8), "};",
            "const opxy::i32 log2m[257] = {", *row(log2m), "};",
            "const opxy::i16 sine[1025] = {", *row(sine, 16), "};",
            "}", "}", ""]
    (ROOT / "tables.cpp").write_text("\n".join(body))
    print("wrote tables.h and tables.cpp")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes FELT's fixed-point tables, defined once: tables.cpp (the data) and
tables.h (their declarations). Pure Python; run it after changing anything
here and commit both.

    python3 -I felt/tools/make_tables.py
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def row(values, per=12):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(values[i:i + per]) + ",")
    return out


def main():
    exp2 = [f"{min(2 ** 31, round(2 ** 30 * 2 ** (i / 256)))}u" for i in range(257)]
    sine = [str(round(32767 * math.sin(2 * math.pi * i / 512))) for i in range(513)]
    # log2 of the whole numbers 1..32, Q16: a partial's place over the fundamental
    log2 = [str(round(65536 * math.log2(1 + i / 256))) for i in range(257)]
    # a raised-cosine contact's reach of a mode: |sinc(u) / (1 - u^2)| at u = f Tc
    # = i / 16, as log2 Q16, held at -6 octaves from its first null (u = 2) on
    reach = []
    for i in range(33):
        u = i / 16
        if i == 0:
            v = 1.0
        elif abs(u - 1) < 1e-9:
            v = 0.5
        else:
            v = abs(math.sin(math.pi * u) / (math.pi * u) / (1 - u * u))
        reach.append(str(max(-6 * 65536, round(65536 * math.log2(max(v, 1e-9)))) if i < 32 else -6 * 65536))
    lnum = [str(round(65536 * math.log2(n))) if n else "0" for n in range(33)]
    data = ["// Generated by tools/make_tables.py: edit the generator, then regenerate.", '#include "tables.h"', "",
            "namespace felt {", "namespace tables {",
            "// 2^(i / 256), Q30.", "const u32 exp2[257] = {", *row(exp2, 8), "};",
            "// sin(2 pi i / 512), Q15, with a guard point.", "const i16 sine[513] = {", *row(sine, 16), "};",
            "// log2(1 + i / 256), Q16.", "const i32 log2[257] = {", *row(log2, 12), "};",
            "// A raised-cosine contact's reach of a mode, log2 |sinc(u) / (1 - u^2)| in Q16, u = f Tc = i / 16.",
            "const i32 reach[33] = {", *row(reach, 11), "};",
            "// log2 n, Q16, for n = 0..32 (0 for n = 0).", "const i32 lnum[33] = {", *row(lnum, 11), "};",
            "}", "}", ""]
    head = ["#pragma once", "// Generated by tools/make_tables.py: FELT's tables, defined once in tables.cpp.",
            "#include <opxy/types.hpp>", "", "namespace felt {", "namespace tables {",
            "using opxy::i16;", "using opxy::i32;", "using opxy::u32;",
            "extern const u32 exp2[257];", "extern const i16 sine[513];", "extern const i32 log2[257];", "extern const i32 reach[33];", "extern const i32 lnum[33];", "}", "}", ""]
    (ROOT / "tables.cpp").write_text("\n".join(data))
    (ROOT / "tables.h").write_text("\n".join(head))
    print("wrote tables.cpp and tables.h")


if __name__ == "__main__":
    main()
